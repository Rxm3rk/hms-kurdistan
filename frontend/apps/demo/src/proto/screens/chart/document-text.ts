export type DocKey = keyof (typeof DOC_TEXT)['en'];

/** A document text in the document's locale, with `{name}` placeholders filled in. */
export function docText(locale: Locale, key: DocKey, vars: Readonly<Record<string, string>> = {}): string {
  const pattern: string = DOC_TEXT[locale][key];
  return pattern.replace(/\{(\w+)\}/g, (match, name: string) => vars[name] ?? match);
}
