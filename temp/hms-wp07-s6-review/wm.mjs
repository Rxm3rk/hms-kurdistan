import { createRequire } from 'node:module';
import path from 'node:path';
const [appDir, shotDir] = process.argv.slice(2);
const require = createRequire(path.join(appDir, 'package.json'));
const { chromium } = require('playwright-core');
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const probe = () => page.evaluate(() => {
  const wm = document.querySelector('[data-testid=demo-watermark]');
  wm.style.pointerEvents = 'auto';
  const r = wm.getBoundingClientRect();
  const pts = [0.05, 0.5, 0.95].map((f) => { const el = document.elementFromPoint(r.left + r.width * f, r.top + r.height / 2); return wm.contains(el) ? 'wm' : (el && (String(el.className) || el.tagName)); });
  wm.style.pointerEvents = '';
  const status = document.querySelector('.hms-modal-stack-status');
  return { rect: [r.top, r.height], pts, ariaHiddenAncestor: !!wm.closest('[aria-hidden=true],[inert]') , stackStatus: status ? status.getBoundingClientRect().toJSON() : null };
});
await page.goto('http://127.0.0.1:4191/demo/banner?locale=ar&fixture=complete', { waitUntil: 'networkidle' });
await page.waitForSelector('section.hms-banner');
const res = { initial: await probe() };
await page.keyboard.press('Control+k');
await page.waitForTimeout(600);
res.palette = { open: !!(await page.$('[role=dialog]')), ...(await probe()) };
await page.screenshot({ path: path.join(shotDir, 'palette-ar.png') });
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
const btns = await page.$$('.hms-demo__actions button');
await btns[0].click();
await page.waitForTimeout(800);
res.sign = await probe();
await page.screenshot({ path: path.join(shotDir, 'sign-ar.png') });
console.log(JSON.stringify(res, null, 2));
await browser.close();
