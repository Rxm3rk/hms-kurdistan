"""The Kotlin the generator writes for one machine (spec §2.3; WP-0.5 contracts §3 and §5).

The output is byte-stable (the same spec always gives the same bytes, LF line endings) and laid out the
way ktlint_official formats it with max_line_length 140 (backend/.editorconfig), so ktlint and detekt
accept it unchanged: no line is longer than 140 columns, long descriptions become ``"..." + "..."``
concatenations and long KDoc wraps, a list that does not fit on its line puts one item per line with a
trailing comma. Three detekt default rules are suppressed where the generated shape trips them by design:
``TooManyFunctions`` on the predicate interface (one function per predicate), ``LargeClass`` on the machine
object (one block per transition) and ``CyclomaticComplexMethod`` on ``holds`` (one ``when`` branch per
predicate).
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from hmstools.statemachines.model import Machine, constant_name
from hmstools.statemachines.targets import Target

GENERATOR_VERSION = 1
GENERATED_MARKER = "// GENERATED by tools/hms statemachines generate"
HEADER_LINE_1 = re.compile(r"^// GENERATED by tools/hms statemachines generate \(generator (\d+)\) from (\S+)$")
HEADER_LINE_2 = re.compile(r"^// sha256 of the canonical spec: ([0-9a-f]{64})$")
MAX_LINE = 140
INDENT = "    "

# Kotlin's hard keywords: a predicate with one of these names cannot be an interface function.
KOTLIN_HARD_KEYWORDS = frozenset((
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
    "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var",
    "when", "while",
))


class EmitError(Exception):
    """The spec cannot be written as Kotlin (a name clash or a keyword)."""


@dataclass(frozen=True)
class GeneratedFile:
    path: str  # repository path
    text: str


def width(line: str) -> int:
    """Columns as ktlint and detekt count them (UTF-16 code units)."""
    return len(line.encode("utf-16-le")) // 2


_ESCAPES = {
    **{code: f"\\u{code:04x}" for code in (*range(0x20), 0x7F)},  # control characters
    ord("\\"): "\\\\", ord('"'): '\\"', ord("$"): "\\$", ord("\n"): "\\n", ord("\r"): "\\r", ord("\t"): "\\t",
}


def _escape(text: str) -> str:
    """``\\``, ``"`` and ``$`` escaped, ``\\n``, ``\\r`` and ``\\t`` as escapes, other control characters as ``\\uXXXX``."""
    return text.translate(_ESCAPES)


def kotlin_string(text: str) -> str:
    """A Kotlin string literal: ``"``, ``\\`` and ``$`` escaped, control characters as escapes."""
    return '"' + _escape(text) + '"'


def _pieces(text: str) -> list[str]:
    """Words with their trailing whitespace; leading whitespace stays with the first word."""
    pieces = re.findall(r"\s*\S+\s*", text)
    return pieces or [text]


def string_lines(text: str, indent: str, suffix: str) -> list[str]:
    """A string expression starting at ``indent`` and ending with ``suffix``: one literal if it fits, otherwise
    a concatenation ``"..." +`` with continuation lines one indent deeper, each line within MAX_LINE. Chunks end
    at word boundaries (the space stays at the end of the chunk); a word longer than a line is cut."""
    single = f"{indent}{kotlin_string(text)}{suffix}"
    if width(single) <= MAX_LINE:
        return [single]
    deeper = indent + INDENT
    # Room for the escaped text of each chunk (2 quotes, then " +" or the suffix).
    first_room = MAX_LINE - width(indent) - 2 - 2
    room = MAX_LINE - width(deeper) - 2 - max(2, width(suffix))
    chunks: list[str] = []
    current, used = "", 0
    for piece in _pieces(text):
        size = width(_escape(piece))
        limit = first_room if not chunks else room
        if current and used + size > limit:
            chunks.append(current)
            current, used, limit = "", 0, room
        if used + size > limit:  # a single word longer than a line: cut it, character by character
            for char in piece:
                char_size = width(_escape(char))
                if used + char_size > limit:
                    chunks.append(current)
                    current, used, limit = "", 0, room
                current += char
                used += char_size
            continue
        current += piece
        used += size
    if current:
        chunks.append(current)
    lines = [f"{indent}{kotlin_string(chunks[0])} +"]
    for number, chunk in enumerate(chunks[1:], start=1):
        end = suffix if number == len(chunks) - 1 else " +"
        lines.append(f"{deeper}{kotlin_string(chunk)}{end}")
    return lines


def _kdoc_text(text: str) -> str:
    """One paragraph of KDoc text: whitespace collapsed, and no ``*/`` or ``/*`` (Kotlin comments nest)."""
    flat = " ".join(text.split())
    return flat.replace("*/", "* /").replace("/*", "/ *")


def kdoc(text: str, indent: str) -> list[str]:
    """A KDoc comment: one line if it fits, otherwise wrapped at word boundaries."""
    body = _kdoc_text(text)
    one = f"{indent}/** {body} */"
    if width(one) <= MAX_LINE:
        return [one]
    lead = f"{indent} * "
    room = MAX_LINE - width(lead)
    words: list[str] = []
    for word in body.split(" "):
        while width(word) > room:  # a word longer than a line: cut it
            cut = len(word)
            while cut > 1 and width(word[:cut]) > room:
                cut -= 1
            words.append(word[:cut])
            word = word[cut:]
        words.append(word)
    lines = [f"{indent}/**"]
    current = ""
    for word in words:
        candidate = f"{current} {word}" if current else word
        if current and width(lead + candidate) > MAX_LINE:
            lines.append(lead + current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(lead + current)
    lines.append(f"{indent} */")
    return lines


def _call(indent: str, head: str, function: str, items: list[str], end: str) -> list[str]:
    """``head function(a, b)end`` on one line if it fits, else ``head`` then the call with one item per line.

    ``head`` is a named argument (``from =``) or a property start; the wrapped form starts the call on the
    next line, one indent deeper, as ktlint's multiline-expression-wrapping places it."""
    one = f"{indent}{head} {function}({', '.join(items)}){end}"
    if width(one) <= MAX_LINE:
        return [one]
    deeper = indent + INDENT
    return [
        f"{indent}{head}",
        f"{deeper}{function}(",
        *(f"{deeper}{INDENT}{item}," for item in items),
        f"{deeper}){end}",
    ]


def _type(base: str, arguments: list[str]) -> str:
    return f"{base}<{', '.join(arguments)}>"


def _type_lines(indent: str, before: str, base: str, arguments: list[str], after: str) -> list[str]:
    """``before base<A, B>after`` on one line if it fits, else the type arguments one per line."""
    one = f"{indent}{before}{_type(base, arguments)}{after}"
    if width(one) <= MAX_LINE:
        return [one]
    return [
        f"{indent}{before}{base}<",
        *(f"{indent}{INDENT}{argument}," for argument in arguments),
        f"{indent}>{after}",
    ]


def header(spec_path: str, sha256: str) -> list[str]:
    return [
        f"{GENERATED_MARKER} (generator {GENERATOR_VERSION}) from {spec_path}",
        f"// sha256 of the canonical spec: {sha256}",
        "// Do not edit: change the spec and run `sh tools/hms statemachines generate`.",
    ]


def _check_names(machine: Machine) -> None:
    for kind, names in (("state", machine.states), ("predicate", list(machine.predicates)), ("effect", list(machine.effects))):
        seen: dict[str, str] = {}
        for name in names:
            constant = constant_name(name)
            if constant in seen:
                raise EmitError(f"the {kind}s {seen[constant]!r} and {name!r} both become the Kotlin name {constant}")
            seen[constant] = name
    for name in machine.predicates:
        if name in KOTLIN_HARD_KEYWORDS:
            raise EmitError(f"the predicate {name!r} is a Kotlin keyword and cannot be an interface function")


def _entries(lines: list[str], entries: list[list[str]]) -> None:
    for entry in entries:
        lines.extend(entry)


def _described_entry(constant: str, identifier: str, description: str) -> list[str]:
    one = f"{INDENT}{constant}({kotlin_string(identifier)}, {kotlin_string(description)}),"
    if width(one) <= MAX_LINE:
        return [one]
    inner = INDENT * 2
    return [
        f"{INDENT}{constant}(",
        f"{inner}{kotlin_string(identifier)},",
        *string_lines(description, inner, ","),
        f"{INDENT}),",
    ]


def _when_entries(predicate: str, names: list[str], indent: str) -> list[str]:
    """The branches of ``holds``: one line each if every one fits; otherwise every branch in braces with a blank
    line between them, as ktlint's when-entry-bracing and blank-line-between-when-conditions rules want."""
    single = [f"{indent}{predicate}.{constant_name(n)} -> predicates.{n}(facts)" for n in names]
    if all(width(line) <= MAX_LINE for line in single):
        return single
    lines: list[str] = []
    for number, name in enumerate(names):
        if number:
            lines.append("")
        lines += [
            f"{indent}{predicate}.{constant_name(name)} -> {{",
            f"{indent}{INDENT}predicates.{name}(facts)",
            f"{indent}}}",
        ]
    return lines


def main_file(machine: Machine, target: Target, spec_path: str, sha256: str) -> GeneratedFile:
    """``<P>Machine.kt`` (contracts §3)."""
    _check_names(machine)
    p = target.prefix
    m = machine.name
    state, command, predicate, effect = f"{p}State", f"{p}Command", f"{p}Predicate", f"{p}Effect"
    kinds = [state, command, predicate, effect]
    lines: list[str] = [
        *header(spec_path, sha256),
        f"package {target.package}",
        "",
        "import hms.kernel.statemachine.MachineSpec",
        "import hms.kernel.statemachine.Outcome",
        "import hms.kernel.statemachine.Transition",
        "",
        *kdoc(f"States of the {m} machine ({spec_path}).", ""),
        f"enum class {state}(",
        f"{INDENT}val id: String,",
        ") {",
    ]
    for name in machine.states:
        lines.append(f"{INDENT}{constant_name(name)}({kotlin_string(name)}),")
    lines += [
        "}",
        "",
        *kdoc(f"Commands of the {m} machine.", ""),
        f"enum class {command} {{",
        *(f"{INDENT}{name}," for name in machine.commands),
        "}",
        "",
        *kdoc(f"Guard predicates of the {m} machine; each is implemented once in [{p}Predicates].", ""),
        f"enum class {predicate}(",
        f"{INDENT}val id: String,",
        f"{INDENT}val description: String,",
        ") {",
    ]
    _entries(lines, [_described_entry(constant_name(n), n, d) for n, d in machine.predicates.items()])
    lines += [
        "}",
        "",
        *kdoc(f"Effects of the {m} machine.", ""),
        f"enum class {effect}(",
        f"{INDENT}val id: String,",
        f"{INDENT}val description: String,",
    ]
    if machine.effects:
        lines.append(") {")
        _entries(lines, [_described_entry(constant_name(n), n, d) for n, d in machine.effects.items()])
        lines.append("}")
    else:
        lines.append(")")
    lines += [
        "",
        *kdoc(f"The guard predicates of the {m} machine, implemented once by the domain ({p}Guards).", ""),
        '@Suppress("TooManyFunctions")',
        f"interface {p}Predicates {{",
    ]
    for number, (name, description) in enumerate(machine.predicates.items()):
        if number:
            lines.append("")
        lines += [*kdoc(description, INDENT), f"{INDENT}fun {name}(facts: {p}Facts): Boolean"]
    lines += [
        "}",
        "",
        *kdoc(f"The executable {m} machine, generated from its specification.", ""),
        '@Suppress("LargeClass")',
        f"object {p}Machine {{",
        f"{INDENT}const val MACHINE: String = {kotlin_string(m)}",
        f"{INDENT}const val VERSION: Int = {machine.version}",
        f"{INDENT}const val SOURCE_SHA256: String = {kotlin_string(sha256)}",
        "",
        *_type_lines(INDENT, "val spec: ", "MachineSpec", kinds, " ="),
    ]
    i2, i3 = INDENT * 2, INDENT * 3
    lines += [
        f"{i2}MachineSpec(",
        f"{i3}machine = MACHINE,",
        f"{i3}version = VERSION,",
        f"{i3}states = {state}.entries,",
        f"{i3}initial = {state}.{constant_name(machine.initial)},",
        *_call(i3, "terminal =", "setOf", [f"{state}.{constant_name(s)}" for s in machine.terminal], ","),
        *_call(i3, "createdBy =", "listOf", [f"{command}.{c}" for c in machine.created_by], ","),
        f"{i3}commands = {command}.entries,",
        f"{i3}transitions =",
        f"{i3}{INDENT}listOf(",
    ]
    i5, i6 = INDENT * 5, INDENT * 6
    for transition in machine.transitions:
        lines += [
            f"{i5}Transition(",
            f"{i6}index = {transition.index},",
            *_call(i6, "from =", "setOf", [f"{state}.{constant_name(s)}" for s in transition.sources], ","),
            f"{i6}on = {command}.{transition.on},",
            *_call(i6, "guard =", "listOf", [f"{predicate}.{constant_name(g)}" for g in transition.guard], ","),
            f"{i6}to = {state}.{constant_name(transition.to)},",
            *_call(i6, "effects =", "listOf", [f"{effect}.{constant_name(e)}" for e in transition.effects], ","),
            f"{i6}proposed = {'true' if machine.is_proposed(transition) else 'false'},",
            f"{i5}),",
        ]
    lines += [
        f"{i3}{INDENT}),",
        f"{i2})",
        "",
        *kdoc("Evaluates [predicate] with the domain's single implementation [predicates].", INDENT),
        f'{INDENT}@Suppress("CyclomaticComplexMethod")',
        f"{INDENT}fun holds(",
        f"{i2}predicate: {predicate},",
        f"{i2}predicates: {p}Predicates,",
        f"{i2}facts: {p}Facts,",
        f"{INDENT}): Boolean =",
        f"{i2}when (predicate) {{",
        *_when_entries(predicate, list(machine.predicates), i3),
        f"{i2}}}",
        "",
        *kdoc("Applies [command] in [state] with [facts]; never changes state unless exactly one guard holds.", INDENT),
        f"{INDENT}fun fire(",
        f"{i2}state: {state},",
        f"{i2}command: {command},",
        f"{i2}predicates: {p}Predicates,",
        f"{i2}facts: {p}Facts,",
    ]
    body = "spec.fire(state, command) { holds(it, predicates, facts) }"
    joined = f"{INDENT}): {_type('Outcome', kinds)} = {body}"
    if width(joined) <= MAX_LINE:
        lines.append(joined)
    else:
        lines += [*_type_lines(INDENT, "): ", "Outcome", kinds, " ="), f"{i2}{body}"]
    lines += ["}", ""]
    return GeneratedFile(target.main_file, "\n".join(lines))


def property_test_file(machine: Machine, target: Target, spec_path: str, sha256: str) -> GeneratedFile:
    """``<P>GeneratedPropertyTest.kt`` (contracts §5)."""
    p = target.prefix
    i2, i3, i4 = INDENT * 2, INDENT * 3, INDENT * 4
    holds = f"{p}Machine.holds(predicate, {p}Guards, facts)"
    one = f"{i4}holds = {{ predicate, facts -> {holds} }},"
    holds_lines = [one] if width(one) <= MAX_LINE else [
        f"{i4}holds = {{ predicate, facts ->",
        f"{i4}{INDENT}{holds}",
        f"{i4}}},",
    ]
    lines = [
        *header(spec_path, sha256),
        f"package {target.package}",
        "",
        "import hms.kernel.testing.statemachine.machineSequenceProperties",
        "import io.kotest.core.spec.style.FunSpec",
        "",
        *kdoc(f"Sequence properties P1 to P7 of the generated {machine.name} model (spec §3.3).", ""),
        f"class {p}GeneratedPropertyTest :",
        f"{INDENT}FunSpec({{",
        f"{i2}include(",
        f"{i3}machineSequenceProperties(",
        f"{i4}name = {p}Machine.MACHINE,",
        f"{i4}spec = {p}Machine.spec,",
        *holds_lines,
        f"{i4}facts = {p}Arbs.facts,",
        f"{i3}),",
        f"{i2})",
        f"{INDENT}}})",
        "",
    ]
    return GeneratedFile(target.property_test_file, "\n".join(lines))


def generate(machine: Machine, target: Target, spec_path: str, sha256: str) -> list[GeneratedFile]:
    """Both generated files of a machine. Raises EmitError."""
    return [main_file(machine, target, spec_path, sha256), property_test_file(machine, target, spec_path, sha256)]
