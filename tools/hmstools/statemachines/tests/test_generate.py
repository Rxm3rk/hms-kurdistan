"""The generated Kotlin (spec §2.3, contracts §3 and §5): golden files, byte stability, layout limits and rule 11.

The golden files under fixtures/golden were checked, outside the repository, with ktlint 1.8.0's standard rules
(ktlint_official, max_line_length 140: lint clean and unchanged by format) and detekt 1.23.8 with
backend/config/detekt/detekt.yml; these tests pin the generator to them. After a deliberate change of the
generator, regenerate them with HMS_UPDATE_GOLDEN=1 and check them with ktlint and detekt again.
"""

from __future__ import annotations

import os
import unittest

from hmstools.common import write_text_lf
from hmstools.statemachines import emit
from hmstools.statemachines.loader import canonical_sha256, load_spec
from hmstools.statemachines.model import build, constant_name
from hmstools.statemachines.tests.harness import FIXTURES, TOY_TARGETS, SandboxCase


class Golden(SandboxCase):
    def test_generated_files_equal_the_golden_files(self) -> None:
        self.box.add("clean")
        result = self.box.generate()
        self.assertPasses(result)
        self.assertEqual(result.counts["generated_files_written"], 4)
        for target in TOY_TARGETS.values():
            for rel in (target.main_file, target.property_test_file):
                actual = (self.box.root / rel).read_bytes().decode("utf-8")
                golden = FIXTURES / "golden" / (rel.rsplit("/", 1)[1] + ".txt")
                if os.environ.get("HMS_UPDATE_GOLDEN") == "1":
                    write_text_lf(golden, actual)
                self.assertEqual(actual, golden.read_text(encoding="utf-8"), rel)

    def test_output_is_byte_stable_and_lf(self) -> None:
        document = load_spec(FIXTURES / "clean" / "toy-light.yaml")
        target = TOY_TARGETS["toy-light"]
        first = emit.generate(build(document), target, "docs/specs/state-machines/toy-light.yaml", canonical_sha256(document))
        second = emit.generate(build(load_spec(FIXTURES / "clean" / "toy-light.yaml")), target,
                               "docs/specs/state-machines/toy-light.yaml", canonical_sha256(document))
        self.assertEqual([f.text for f in first], [f.text for f in second])
        for generated in first:
            self.assertNotIn("\r", generated.text)
            self.assertTrue(generated.text.endswith("}\n") or generated.text.endswith("})\n"))
            self.assertFalse(generated.text.endswith("\n\n"))

    def test_regenerating_writes_nothing(self) -> None:
        self.box.add("clean")
        self.box.generate()
        again = self.box.generate()
        self.assertPasses(again)
        self.assertEqual(again.counts["generated_files_written"], 0)

    def test_paths_header_and_contract_names(self) -> None:
        self.box.add("clean", "toy-light.yaml", "toy-light.md")
        self.box.generate()
        target = TOY_TARGETS["toy-light"]
        self.assertEqual(target.main_file, "backend/modules/adt/src/main/kotlin/hms/adt/domain/toylight/ToyLightMachine.kt")
        self.assertEqual(target.property_test_file,
                         "backend/modules/adt/src/propertyTest/kotlin/hms/adt/domain/toylight/ToyLightGeneratedPropertyTest.kt")
        text = (self.box.root / target.main_file).read_text(encoding="utf-8")
        sha = canonical_sha256(load_spec(FIXTURES / "clean" / "toy-light.yaml"))
        lines = text.splitlines()
        self.assertEqual(lines[0], "// GENERATED by tools/hms statemachines generate (generator 1) from docs/specs/state-machines/toy-light.yaml")
        self.assertEqual(lines[1], f"// sha256 of the canonical spec: {sha}")
        self.assertIn(f'    const val SOURCE_SHA256: String = "{sha}"', lines)
        for fragment in ("enum class ToyLightState(", "enum class ToyLightCommand {", "enum class ToyLightPredicate(",
                         "enum class ToyLightEffect(", "interface ToyLightPredicates {", "object ToyLightMachine {",
                         "    fun powerAvailable(facts: ToyLightFacts): Boolean", '    const val MACHINE: String = "toy-light"',
                         "    const val VERSION: Int = 1", "            createdBy = listOf(ToyLightCommand.Install),",
                         "            initial = ToyLightState.OFF,", "            terminal = setOf(ToyLightState.RETIRED),"):
            self.assertIn(fragment, text)
        test = (self.box.root / target.property_test_file).read_text(encoding="utf-8")
        self.assertIn("holds = { predicate, facts -> ToyLightMachine.holds(predicate, ToyLightGuards, facts) },", test)
        self.assertIn("facts = ToyLightArbs.facts,", test)

    def test_star_expands_to_every_state_but_to_and_proposed_follows_the_flag_and_the_list(self) -> None:
        machine = build(load_spec(FIXTURES / "clean" / "toy-light.yaml"))
        star = machine.transitions[2]
        self.assertEqual(star.sources, ("off", "on"))
        self.assertEqual(star.edges, ("*→retired",))
        # [0] neither flagged nor listed; [1] its own proposed: true; [2] its edge *→retired is listed; [3] neither.
        self.assertEqual([machine.is_proposed(t) for t in machine.transitions], [False, True, True, False])
        text = emit.main_file(machine, TOY_TARGETS["toy-light"], "x.yaml", "0" * 64).text
        self.assertEqual([line.strip() for line in text.splitlines() if "proposed =" in line],
                         ["proposed = false,", "proposed = true,", "proposed = true,", "proposed = false,"])

    def test_commands_put_creation_commands_first(self) -> None:
        machine = build(load_spec(FIXTURES / "clean" / "toy-light.yaml"))
        self.assertEqual(machine.commands, ("Install", "SwitchOn", "SwitchOff", "Retire", "Reinstate"))


class Layout(unittest.TestCase):
    def test_every_line_fits_140_columns(self) -> None:
        for name in ("toy-light", "toy-wrapping-demonstration"):
            document = load_spec(FIXTURES / "clean" / f"{name}.yaml")
            for generated in emit.generate(build(document), TOY_TARGETS[name], f"docs/specs/state-machines/{name}.yaml", "0" * 64):
                for number, line in enumerate(generated.text.splitlines(), start=1):
                    self.assertLessEqual(emit.width(line), 140, f"{generated.path}:{number}")
                    self.assertEqual(line, line.rstrip(), f"{generated.path}:{number} trailing space")

    def test_escaping(self) -> None:
        self.assertEqual(emit.kotlin_string('a "b" \\ $c\n\t\x01'), '"a \\"b\\" \\\\ \\$c\\n\\t\\u0001"')

    def test_long_strings_split_at_word_boundaries_and_rejoin(self) -> None:
        text = "word " * 80 + "end with $ and \"quotes\""
        lines = emit.string_lines(text, "        ", ",")
        self.assertGreater(len(lines), 2)
        self.assertTrue(all(emit.width(line) <= 140 for line in lines))
        self.assertTrue(lines[0].endswith('" +') and lines[-1].endswith('",'))
        self.assertTrue(all(line.startswith("            \"") for line in lines[1:]))
        literals = [line.strip().removesuffix(" +").removesuffix(",") for line in lines]
        joined = "".join(lit[1:-1] for lit in literals)
        self.assertEqual(joined, emit._escape(text))  # noqa: SLF001

    def test_kdoc_never_closes_or_opens_a_comment(self) -> None:
        lines = emit.kdoc("ends */ here and /* opens " + "x " * 100, "    ")
        body = "\n".join(lines[1:-1])
        self.assertNotIn("*/", body)
        self.assertNotIn("/*", body)
        self.assertTrue(all(emit.width(line) <= 140 for line in lines))
        self.assertEqual(emit.kdoc("short", ""), ["/** short */"])

    def test_constant_names(self) -> None:
        self.assertEqual(constant_name("in-progress"), "IN_PROGRESS")
        self.assertEqual(constant_name("activeVerifiedOrder"), "ACTIVE_VERIFIED_ORDER")
        self.assertNotEqual(constant_name("aBC"), constant_name("aBc"))

    def test_a_keyword_predicate_cannot_be_generated(self) -> None:
        document = load_spec(FIXTURES / "clean" / "toy-light.yaml")
        document["predicates"]["in"] = "a keyword"
        with self.assertRaisesRegex(emit.EmitError, "'in' is a Kotlin keyword"):
            emit.main_file(build(document), TOY_TARGETS["toy-light"], "x.yaml", "0" * 64)


class Rule11(SandboxCase):
    def setUp(self) -> None:
        super().setUp()
        self.box.add("clean", "toy-light.yaml", "toy-light.md")
        self.box.install_kotlin("toy-light")
        self.assertPasses(self.box.generate())
        self.main = self.box.root / TOY_TARGETS["toy-light"].main_file

    def test_current_files_pass_generate_check(self) -> None:
        result = self.box.check(rule_11_only=True)
        self.assertPasses(result)
        self.assertEqual(result.check, "state-machines-generate")

    def test_missing_file(self) -> None:
        self.main.unlink()
        self.assertFailsWith(self.box.check(rule_11_only=True), "rule 11: backend/modules/adt/src/main/kotlin/hms/adt/domain/toylight/"
                             "ToyLightMachine.kt is missing; run sh tools/hms statemachines generate")

    def test_spec_changed_since_generation(self) -> None:
        spec = self.box.specs / "toy-light.yaml"
        spec.write_text(spec.read_text(encoding="utf-8").replace("mains or generator power is present", "mains power is present"),
                        encoding="utf-8")
        self.assertFailsWith(self.box.check(), "ToyLightMachine.kt was generated from other spec content")

    def test_comment_change_in_the_spec_keeps_the_files_current(self) -> None:
        spec = self.box.specs / "toy-light.yaml"
        spec.write_text("# a new comment\n" + spec.read_text(encoding="utf-8").replace("states: [off, on, retired]", "states:\n  [off, on, retired]"),
                        encoding="utf-8")
        self.assertPasses(self.box.check())

    def test_hand_edit(self) -> None:
        self.main.write_text(self.main.read_text(encoding="utf-8").replace("const val VERSION: Int = 1", "const val VERSION: Int = 2"),
                             encoding="utf-8", newline="\n")
        self.assertFailsWith(self.box.check(), "ToyLightMachine.kt differs from the generator's output for the same spec content")

    def test_reordered_predicates_are_not_called_a_hand_edit(self) -> None:
        # py-09: the canonical sha256 sorts keys, the Kotlin keeps the spec's order.
        spec = self.box.specs / "toy-light.yaml"
        text = spec.read_text(encoding="utf-8")
        lines = text.splitlines(keepends=True)
        first = next(i for i, line in enumerate(lines) if line.startswith("  powerAvailable:"))
        lines[first], lines[first + 1] = lines[first + 1], lines[first]
        spec.write_text("".join(lines), encoding="utf-8", newline="\n")
        self.assertEqual(canonical_sha256(load_spec(spec)), canonical_sha256(load_spec(FIXTURES / "clean" / "toy-light.yaml")))
        result = self.box.check()
        self.assertFailsWith(result, "ToyLightMachine.kt has the generator's lines in another order: the order of the spec's predicates or "
                             "effects changed since it was generated")
        self.assertNotIn("edited by hand?", "\n".join(result.errors))

    def test_other_generator_version(self) -> None:
        self.main.write_text(self.main.read_text(encoding="utf-8").replace("(generator 1)", "(generator 0)"), encoding="utf-8", newline="\n")
        self.assertFailsWith(self.box.check(), "ToyLightMachine.kt was written by generator 0; this is generator 1")

    def test_crlf(self) -> None:
        self.main.write_bytes(self.main.read_bytes().replace(b"\n", b"\r\n"))
        self.assertFailsWith(self.box.check(), "ToyLightMachine.kt has CRLF line endings")

    def test_orphan(self) -> None:
        (self.box.specs / "toy-light.yaml").unlink()
        self.assertFailsWith(self.box.check(), "ToyLightMachine.kt: rule 11: a generated file whose spec does not exist")

    def test_a_failing_spec_is_not_generated(self) -> None:
        spec = self.box.specs / "toy-light.yaml"
        spec.write_text(spec.read_text(encoding="utf-8").replace("guard: [powerAvailable, lampIntact]", "guard: [powerAvailable, nope]"),
                        encoding="utf-8")
        before = self.main.read_bytes()
        self.assertFailsWith(self.box.generate(), "not generated: the spec fails the rules above")
        self.assertEqual(self.main.read_bytes(), before)
        self.assertFailsWith(self.box.check(rule_11_only=True), "rule 11: the generated files cannot be checked while the spec fails rules 1 to 10")


if __name__ == "__main__":
    unittest.main()
