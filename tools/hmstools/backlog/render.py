"""Render docs/program/BACKLOG.md from backlog.yaml (plus the A.18 totals and section names from the plan)."""

from __future__ import annotations

from typing import Any

from hmstools.backlog.plan import STATUSES, Mapping, Plan
from hmstools.backlog.records import key_of
from hmstools.backlog.source import PHASES, SIZE_CODES, size_reading
from hmstools.backlog.totals import (
    a18_internal_problems,
    compare_a18,
    features_only,
    is_part,
    phase_counts,
    status_counts,
    without_work_package,
)

DASH = "—"


def _cell(value: Any) -> str:
    text = "" if value is None else str(value)
    return text.replace("\r", " ").replace("\n", " ").replace("|", "\\|")


def _list_cell(values: Any, sep: str) -> str:
    if not values:
        return DASH
    if not isinstance(values, list):
        return _cell(values)
    return _cell(sep.join(str(v) for v in values))


def _ids(records: list[dict[str, Any]]) -> str:
    return ", ".join(f"`{key_of(r)}`" for r in records) if records else "none"


def _signed(n: int) -> str:
    return f"+{n}" if n > 0 else str(n)


def render_markdown(records: list[dict[str, Any]], plan: Plan, mapping: Mapping) -> str:
    features = features_only(records)
    parts = [r for r in records if is_part(r)]
    statuses = list(STATUSES) + sorted({str(r.get("status")) for r in records} - set(STATUSES))
    out: list[str] = []
    add = out.append

    add("<!-- Generated by 'tools/hms backlog render' from docs/program/backlog.yaml. Do not edit. -->")
    add("")
    add("# Backlog of record")
    add("")
    add(
        "**Generated, do not edit.** This file is rendered from `docs/program/backlog.yaml`, which "
        "`tools/hms backlog generate` builds from BUILD-PROMPT.md Appendix A (feature tables A.1 to A.17), with "
        "work packages taken from §21. To change a status, work package, test, hazard or note, edit "
        "`backlog.yaml` and run `tools/hms backlog render`. `tools/hms backlog check` fails when this file is "
        "out of date."
    )
    add("")
    add(
        "Statuses (§3.1): `todo`, `spec`, `in-progress`, `built` (Definition of Done items 1 to 9 true with "
        "evidence, §22.1) and `verified` (item 10 also true). Stance: B build, I integrate, P partner or "
        "licence; † marks a domain-level stance."
    )
    add("")

    # Summary ---------------------------------------------------------------------------------------------
    add("## Summary")
    add("")
    add(
        f"{len(features)} feature IDs in {len(plan.sections)} groups, plus {len(parts)} part rows that carry part "
        f"of a feature's scope in another phase ({_ids(parts)}). As in A.18, part rows count towards "
        "engineer-weeks but not towards feature IDs."
    )
    add("")
    add("### By phase")
    add("")
    add("| Phase | Feature IDs | " + " | ".join(statuses) + " |")
    add("|---|---" + "|---" * len(statuses) + "|")
    by_phase = phase_counts(records)
    for phase in PHASES:
        in_phase = [r for r in features if r.get("phase") == phase]
        counts = status_counts(in_phase)
        add(f"| {phase} | {by_phase.get(phase, 0)} | " + " | ".join(str(counts.get(s, 0)) for s in statuses) + " |")
    total_counts = status_counts(records)
    add(f"| **All** | **{len(features)}** | " + " | ".join(f"**{total_counts.get(s, 0)}**" for s in statuses) + " |")
    add("")
    add("### By status")
    add("")
    add("| Status | Feature IDs | Part rows |")
    add("|---|---|---|")
    part_counts = {s: sum(1 for r in parts if str(r.get("status")) == s) for s in statuses}
    for status in statuses:
        label = status if status in STATUSES else f"{status} (not a valid status)"
        add(f"| {_cell(label)} | {total_counts.get(status, 0)} | {part_counts[status]} |")
    add("")
    add("### Without a work package")
    add("")
    no_wp = [r for r in without_work_package(features)]
    dropped = [r for r in no_wp if r.get("phase") == "DROPPED-K"]
    live = [r for r in no_wp if r.get("phase") != "DROPPED-K"]
    add(
        f"{len(no_wp)} of {len(features)} feature IDs are named in no §21 work package: {len(dropped)} DROPPED-K "
        f"and {len(live)} in other phases."
    )
    add("")
    add(f"- Not dropped ({len(live)}): {_ids(live)}")
    add(f"- DROPPED-K ({len(dropped)}): {_ids(dropped)}")
    add(f"- Part rows without a work package: {_ids(without_work_package(parts))}")
    add("")
    add("### Placements marked [P]")
    add("")
    marked = [r for r in records if r.get("placement_marked")]
    add(
        "Rows whose Appendix A note carries [P], a safety-driven placement by BUILD-PROMPT.md. Follow the "
        f"placement and keep it open in `OPEN-QUESTIONS.md` until a human confirms it (§1): {_ids(marked)}."
    )
    add("")
    add("### Work-package references not mapped to a feature")
    add("")
    if mapping.wildcards or mapping.unknown:
        for ref in mapping.wildcards:
            add(
                f"- {ref.wp} (BUILD-PROMPT.md line {ref.line}) names `{ref.target}` {_cell(ref.qualifier or '')}: a "
                "wildcard that names no single feature, so it is not attached to any row."
            )
        for ref in mapping.unknown:
            add(f"- {ref.wp} (BUILD-PROMPT.md line {ref.line}) names `{ref.target}`, which is not in Appendix A.")
    else:
        add("None.")
    add("")

    # A.18 ------------------------------------------------------------------------------------------------
    add("## Check against A.18")
    add("")
    rows = compare_a18(records, plan.a18)
    add(
        "| Phase | Feature IDs (A.18) | Feature IDs (backlog) | Difference | Engineer-weeks (A.18) | "
        "Engineer-weeks (backlog) | Difference |"
    )
    add("|---|---|---|---|---|---|---|")
    for row in rows:
        add(
            f"| {_cell(row.label)} | {row.a18_count} | {row.count} | {_signed(row.count_diff)} | {row.a18_ew} | "
            f"{row.ew} | {_signed(row.ew_diff)} |"
        )
    add("")
    count_bad = [r for r in rows if r.count_diff]
    ew_bad = [r for r in rows if r.ew_diff]
    if not count_bad and not ew_bad:
        add("Every feature-ID count and engineer-week sum matches A.18.")
    for row in count_bad:
        add(f"- Feature IDs differ for {row.label}: A.18 {row.a18_count}, backlog {row.count} ({_signed(row.count_diff)}).")
    for row in ew_bad:
        why = f" Explained by {row.explanation}." if row.explanation else " Not explained by A.18's note."
        add(f"- Engineer-weeks differ for {row.label}: A.18 {row.a18_ew}, backlog {row.ew} ({_signed(row.ew_diff)}).{why}")
    for problem in a18_internal_problems(plan.a18):
        add(f"- {problem}.")
    add("")
    codes = ", ".join(f"{code} = {ew}" for code, ew in SIZE_CODES.items())
    add(
        f"Size rule: {codes} engineer-weeks; a combined code such as L+M is the sum; `≈n ew` is n. A bracketed "
        "annotation `(BP …)` records BP's size history and does not change the count; `(−n)` subtracts n; "
        "`(+n net)` counts n, the net addition over the feature the row extends. Rows whose size is not a plain "
        "code:"
    )
    add("")
    add("| ID | Phase | Size | Engineer-weeks counted | Reading |")
    add("|---|---|---|---|---|")
    for record in records:
        reading = size_reading(str(record.get("size")))
        if not reading.plain:
            add(
                f"| `{_cell(key_of(record))}` | {_cell(record.get('phase'))} | {_cell(record.get('size'))} | "
                f"{reading.ew} | {_cell(reading.reading)} |"
            )
    add("")
    face = [r for r in rows if r.face_diff]
    if face:
        listed = "; ".join(f"{r.label} {r.face_ew} ({_signed(r.face_diff)})" for r in face)
        add(
            "At face value (the size code alone, ignoring the bracketed annotations) the sums would differ from "
            f"A.18: {listed}. A.18 matches the annotated reading above, not the face value."
            if not ew_bad
            else f"At face value (the size code alone, ignoring the bracketed annotations): {listed}."
        )
    else:
        add("At face value (the size code alone, ignoring the bracketed annotations) the sums also match A.18.")
    add("")
    if plan.a18.note:
        add(f"A.18's note (BUILD-PROMPT.md line {plan.a18.note_line}): \"{plan.a18.note}\"")
    else:
        add("A.18 has no note after its table.")
    add("")

    # Groups ----------------------------------------------------------------------------------------------
    names = {s.section: s for s in plan.sections}
    order = [s.section for s in plan.sections]
    in_yaml = sorted({str(r.get("section")) for r in records} - set(order))
    for section in order + in_yaml:
        group_rows = [r for r in records if r.get("section") == section]
        if not group_rows:
            continue
        info = names.get(section)
        title = f"{section} {info.group}: {info.name}" if info else f"{section} (not an Appendix A section)"
        add(f"## {_cell(title)}")
        add("")
        add("| ID | Title | Size | Phase | Stance | Status | Work packages | Tests | Hazards |")
        add("|---|---|---|---|---|---|---|---|---|")
        for r in group_rows:
            stance = f"{r.get('stance')}{'†' if r.get('domain_level') else ''}"
            add(
                f"| `{_cell(key_of(r))}` | {_cell(r.get('title'))} | {_cell(r.get('size'))} | {_cell(r.get('phase'))} | "
                f"{_cell(stance)} | {_cell(r.get('status'))} | {_list_cell(r.get('work_packages'), '; ')} | "
                f"{_list_cell(r.get('tests'), '; ')} | {_list_cell(r.get('hazards'), ', ')} |"
            )
        add("")
    return "\n".join(out).rstrip("\n") + "\n"
