"""render and spot-check output."""

from __future__ import annotations

import unittest

from hmstools.backlog.commands import generate, render, spot_check
from hmstools.backlog.paths import EnvironmentProblem
from hmstools.backlog.records import load_records
from hmstools.backlog.tests.synthetic import PLAN, SyntheticRepo


class RenderTest(unittest.TestCase):
    def render_plan(self, plan: str = PLAN) -> str:
        repo = SyntheticRepo(plan)
        try:
            generate(repo.paths)
            render(repo.paths)
            data = repo.paths.markdown.read_bytes()
        finally:
            repo.cleanup()
        self.assertNotIn(b"\r", data)
        return data.decode("utf-8")

    def test_header_summary_and_group_tables(self) -> None:
        text = self.render_plan()
        self.assertTrue(text.startswith("<!-- Generated by 'tools/hms backlog render'"))
        self.assertIn("**Generated, do not edit.**", text)
        self.assertIn("| R1 | 7 | 7 | 0 | 0 | 0 | 0 |", text)
        self.assertIn("| todo | 15 | 1 |", text)
        self.assertIn("## A.1 PLT: Platform/NFR", text)
        self.assertIn("| ID | Title | Size | Phase | Stance | Status | Work packages | Tests | Hazards |", text)
        self.assertIn("| `PLT-CORE-02` | Enterprise \\| hierarchy | L | R1 | B | todo | WP-0.3; WP-1.1 (full) | — | — |", text)
        self.assertIn("| `KRI-ID-01` | Iraqi identity | L (+12 net) | R1 | B+I† |", text)
        self.assertIn("| `RCM-SCH-01 · part: scheme` | Scheme billing | ≈3 ew | P2 | B | todo | Phase 5 (the scheme part) |", text)
        self.assertIn("Every feature-ID count and engineer-week sum matches A.18.", text)
        self.assertIn("- Not dropped (0): none", text)
        self.assertIn("`PLT-CORE-02`", text.split("### Placements marked [P]")[1].split("###")[0])

    def test_a18_difference_shows_both_numbers(self) -> None:
        text = self.render_plan(PLAN.replace("| R1 | 7 | 143 |", "| R1 | 7 | 133 |"))
        self.assertIn("| R1 | 7 | 7 | 0 | 133 | 143 | +10 |", text)
        self.assertIn("Engineer-weeks differ for R1: A.18 133, backlog 143 (+10). Not explained by A.18's note.", text)

    def test_face_value_reading_is_shown(self) -> None:
        text = self.render_plan()
        # Face value: RCM-SCH-01 counts 8 instead of 5 and KRI-ID-01 20 instead of 12, so R1 is 11 higher.
        self.assertIn("R1 154 (+11)", text)
        self.assertIn("| `KRI-ID-01` | R1 | L (+12 net) | 12 |", text)

    def test_render_is_deterministic(self) -> None:
        self.assertEqual(self.render_plan(), self.render_plan())


class SpotCheckTest(unittest.TestCase):
    def setUp(self) -> None:
        self.repo = SyntheticRepo()
        generate(self.repo.paths)

    def tearDown(self) -> None:
        self.repo.cleanup()

    def test_rows_beside_records(self) -> None:
        out = spot_check(self.repo.paths, seed=7, count=16)
        for record in load_records(self.repo.paths.backlog):
            self.assertIn(f"-> title: \"{record['title']}\"", out)
        self.assertIn("raw row: | `KRI-ID-01` | Iraqi identity | L (+12 net) | R1 | B+I† |", out)
        self.assertIn("-> domain_level: true", out)
        self.assertIn("(counts 12 engineer-weeks", out)

    def test_same_seed_same_rows(self) -> None:
        first = spot_check(self.repo.paths, seed=20261018, count=5)
        self.assertEqual(first, spot_check(self.repo.paths, seed=20261018, count=5))
        self.assertNotEqual(first, spot_check(self.repo.paths, seed=1, count=5))

    def test_count_out_of_range(self) -> None:
        with self.assertRaises(EnvironmentProblem):
            spot_check(self.repo.paths, seed=1, count=0)


if __name__ == "__main__":
    unittest.main()
